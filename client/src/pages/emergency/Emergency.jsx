import { useState, useEffect } from 'react';
import { getProfiles } from '../../api/profiles';
import { getEmergencyProfile } from '../../api/emergency';
import LoadingSpinner from '../../components/LoadingSpinner';
import './Emergency.css';

const Emergency = () => {
  const [profiles, setProfiles] = useState([]);
  const [selectedProfileId, setSelectedProfileId] = useState('');
  const [emergencyData, setEmergencyData] = useState(null);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    const fetchProfiles = async () => {
      try {
        const res = await getProfiles();
        const profs = res.data.data || [];
        setProfiles(profs);
        if (profs.length > 0) {
          setSelectedProfileId(profs[0]._id);
        }
      } catch (err) {
        console.error(err);
      } finally {
        setLoading(false);
      }
    };
    fetchProfiles();
  }, []);

  useEffect(() => {
    if (!selectedProfileId) return;
    const fetchEmergencyData = async () => {
      try {
        const res = await getEmergencyProfile(selectedProfileId);
        setEmergencyData(res.data.data);
      } catch (err) {
        console.error(err);
      }
    };
    fetchEmergencyData();
  }, [selectedProfileId]);

  const handlePrint = () => {
    window.print();
  };

  if (loading) return <LoadingSpinner fullPage />;

  return (
    <div className="emergency-page">
      <div className="no-print">
        <div className="emergency-header">
          <div>
            <h1 style={{ fontSize: '1.8rem', fontWeight: 800 }}>🚨 Emergency Information</h1>
            <p style={{ color: 'var(--text-secondary)' }}>Print this sheet to give to doctors or paramedics in an emergency.</p>
          </div>
          <button className="btn btn-primary" onClick={handlePrint} disabled={!emergencyData}>
            🖨️ Print Card
          </button>
        </div>

        <div className="selector-bar">
          <label style={{ fontWeight: 600 }}>Select Family Member:</label>
          <select 
            value={selectedProfileId} 
            onChange={(e) => setSelectedProfileId(e.target.value)}
          >
            {profiles.map(p => (
              <option key={p._id} value={p._id}>{p.name}</option>
            ))}
          </select>
        </div>
      </div>

      {emergencyData && (
        <div className="print-area emergency-card">
          <div className="emergency-card-header">
            <div className="emergency-title">⚕️ Medical Emergency Info</div>
            <div className="profile-info">
              <div className="profile-name">{emergencyData.profile.name}</div>
              <div className="profile-age">
                Age: {emergencyData.profile.age} · {emergencyData.profile.gender}
                <br/>
                Blood: {emergencyData.profile.bloodGroup || 'N/A'}
              </div>
            </div>
          </div>

          <div className="info-section">
            <h3>Known Allergies</h3>
            <div className="allergies-box">
              {emergencyData.profile.allergies?.length > 0 
                ? emergencyData.profile.allergies.join(', ')
                : 'No known allergies'}
            </div>
          </div>

          <div className="info-section">
            <h3>Current Medications</h3>
            {emergencyData.medicines.length === 0 ? (
              <p>No active medications on file.</p>
            ) : (
              <div className="med-list">
                {emergencyData.medicines.map(med => (
                  <div className="med-item" key={med._id}>
                    <div>
                      <div className="med-item-name">{med.name}</div>
                      <div className="med-item-generic">{med.genericName || med.activeIngredients?.join(', ')}</div>
                    </div>
                    <div>
                      <div style={{ fontSize: '0.8rem', color: '#718096', textTransform: 'uppercase' }}>Schedule</div>
                      <div className="med-item-times">
                        {med.scheduleTimes && med.scheduleTimes.length > 0 
                          ? med.scheduleTimes.join(', ') 
                          : 'As needed / PRN'}
                      </div>
                    </div>
                    <div>
                      <div style={{ fontSize: '0.8rem', color: '#718096', textTransform: 'uppercase' }}>Used For</div>
                      <div className="med-item-uses">{med.uses || 'Not specified'}</div>
                    </div>
                  </div>
                ))}
              </div>
            )}
          </div>
          
          <div style={{ marginTop: '3rem', fontSize: '0.8rem', color: '#718096', textAlign: 'center' }}>
            Generated by MediCabinet on {new Date().toLocaleDateString()}
          </div>
        </div>
      )}
    </div>
  );
};

export default Emergency;
